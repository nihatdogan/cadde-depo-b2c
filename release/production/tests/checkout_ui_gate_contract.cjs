'use strict';
const assert=require('node:assert/strict');
const client=require('../../../assets/cadde-checkout-v3.js');
const {randomUUID}=require('node:crypto');
const stored=new Map(),calls=[];
const ui=()=>({button:{disabled:false},status:{textContent:'',hidden:true},challenge:{hidden:true},turnstile:{},whatsapp:{hidden:true,href:'',removeAttribute(k){delete this[k];}}});
let post=async()=>{throw Error('network ambiguous');};
global.localStorage={getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,v)};
global.crypto={randomUUID};
global.document={};
global.fetch=async(url,opts={})=>{
 calls.push({url,opts});
 if(opts.method==='GET')return {status:200,json:async()=>({enabled:true,siteKey:'ci-public-key'})};
 return post(JSON.parse(opts.body));
};
global.turnstile={render:(target,config)=>{global.challenge=config;return 0;},reset:()=>{}};
(async()=>{
 const preview=client.createClient({isProduction:false});
 assert.equal((await preview.check()).enabled,false);
 assert.equal(calls.length,0,'Preview attempted an API call');
 const elements=ui(),cart=[{id:5,now:33000,nm:'Synthetic Test'}];
 const checkout=client.createClient({isProduction:true,elements,getCart:()=>cart,fmt:x=>String(x),waHref:s=>'https://wa.me/example?text='+encodeURIComponent(s)});
 assert.equal((await checkout.check()).enabled,true);
 assert.equal(checkout.receipt(201,{request_id:randomUUID(),total:33000,reused:false},33000),true);
 assert.equal(checkout.receipt(200,{request_id:randomUUID(),total:33000,reused:true},33000),true);
 assert.equal(checkout.receipt(201,{request_id:randomUUID(),total:33001,reused:false},33000),false);
 await checkout.prepare();
 assert.equal(elements.button.disabled,true,'Should require Turnstile');
 global.challenge.callback('synthetic-token-1');
 await checkout.submit();
 assert.equal(elements.whatsapp.hidden,true,'Ambiguous request opened WhatsApp');
 const first=JSON.parse(stored.get('cd_checkout_v3_intent'));
 assert.equal(first.state,'pending');
 assert.equal(checkout.canEdit(),false,'Uncertain order allowed cart change');
 post=async body=>({status:200,json:async()=>({request_id:randomUUID(),total:33000,reused:true})});
 global.challenge.callback('synthetic-token-2');
 await checkout.submit();
 const sent=calls.filter(x=>x.opts.method==='POST').map(x=>JSON.parse(x.opts.body));
 assert.equal(sent.length,2);
 assert.equal(sent[0].idempotencyKey,sent[1].idempotencyKey,'Retry minted a new idempotency key');
 assert.equal(sent[0].visitorId,sent[1].visitorId,'Retry minted a new visitor');
 assert.equal(elements.whatsapp.hidden,false,'Verified order did not unlock WhatsApp');
 assert.match(elements.whatsapp.href,/Talep%20kodu/);
 assert.equal(JSON.parse(stored.get('cd_checkout_v3_intent')).state,'saved');
 assert.equal(checkout.canEdit(),true);
 const prevCount=calls.length;
 await checkout.submit();
 assert.equal(calls.length,prevCount,'Saved order submitted again');
 console.log('CHECKOUT_UI_GATE_RETRY_AND_WHATSAPP_PASS');
})().catch(e=>{console.error(e);process.exitCode=1;});
